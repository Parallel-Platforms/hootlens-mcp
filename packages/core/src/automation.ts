/*
 * Automated visit detection, shared by the tracker, the collector and the dashboard.
 *
 * The tracker sends a small bitmask of observed signals with each batch. The collector adds the signals it
 * can see itself (the request's user agent, click timing in the batch) and decides from the combined bits.
 * Every decision is explainable: a reason is a named signal that was observed, never a score.
 *
 * Nothing here identifies a person or a device. The signals describe how input arrived (how fast, how
 * regular, whether a press came first) and whether the browser says it is automated. Viewport size and
 * device class are never evidence on their own.
 *
 * This module has no dependencies so the browser bundle can import it.
 */

/** Signal names stored with a recording and sent to the API. */
export const AUTOMATION_REASONS = [
  'webdriver', 'headless', 'bot_agent', 'rapid_input', 'metronome',
  'untrusted_events', 'unpaired_clicks', 'no_pointer_movement', 'hidden_visit', 'same_spot', 'sustained_clicking',
] as const;
export type AutomationReason = typeof AUTOMATION_REASONS[number];

/** Bit of each reason. The tracker may set the low nine; the collector sets the rest itself. */
export const AUTOMATION_BITS: Readonly<Record<AutomationReason, number>> = {
  webdriver: 1 << 0,
  headless: 1 << 1,
  bot_agent: 1 << 2,
  rapid_input: 1 << 3,
  metronome: 1 << 4,
  untrusted_events: 1 << 5,
  unpaired_clicks: 1 << 6,
  no_pointer_movement: 1 << 7,
  hidden_visit: 1 << 8,
  same_spot: 1 << 9,
  sustained_clicking: 1 << 10,
};
/** Every bit a batch's `auto` field may carry. Anything above is dropped. */
export const AUTOMATION_MASK = Object.values(AUTOMATION_BITS).reduce((all, bit) => all | bit, 0);

/** One of these alone makes a visit automated. */
export const STRONG_REASONS: readonly AutomationReason[] = ['webdriver', 'headless', 'bot_agent', 'rapid_input', 'metronome'];
/** Several of these together make a visit suspected. One alone is not enough. */
export const WEAK_REASONS: readonly AutomationReason[] = ['untrusted_events', 'unpaired_clicks', 'no_pointer_movement', 'hidden_visit', 'same_spot', 'sustained_clicking'];
/** Weak signals needed for a suspected visit. */
export const SUSPECTED_MIN_WEAK = 2;

export type AutomationLevel = 'automated' | 'suspected';
export interface AutomationVerdict { level: AutomationLevel; reasons: AutomationReason[]; }

export function reasonsOf(bits: number): AutomationReason[] {
  return AUTOMATION_REASONS.filter(reason => (bits & AUTOMATION_BITS[reason]) !== 0);
}

/** The decision for a set of observed signals, or undefined when the visit looks like a person. */
export function classifyAutomation(bits: number | undefined): AutomationVerdict | undefined {
  const reasons = reasonsOf(Number.isInteger(bits) ? (bits as number) & AUTOMATION_MASK : 0);
  if (reasons.some(reason => STRONG_REASONS.includes(reason))) return { level: 'automated', reasons };
  if (reasons.filter(reason => WEAK_REASONS.includes(reason)).length >= SUSPECTED_MIN_WEAK) return { level: 'suspected', reasons };
  return undefined;
}

