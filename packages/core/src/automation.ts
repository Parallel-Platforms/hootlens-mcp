/* ------------------------------------------------------------------ user agents */

/** Browsers driven by automation tooling. They run pages like a visitor would, so their visits are kept and labelled. */
const AUTOMATION_AGENT = /(?:phantomjs|slimerjs|selenium|webdriver|puppeteer|playwright|chrome-lighthouse|pagespeed|gtmetrix|nightmare|zombie\.js|htmlunit)/i;
const HEADLESS_AGENT = /headless/i;

/**
 * The signals a browser reports about being driven by tooling: a headless user agent or brand, or the name of an
 * automation tool. The tracker uses this alone, so the crawler list stays on the server.
 */
export function toolAgentBits(userAgent: string | undefined, brands?: readonly string[]): number {
  let bits = 0;
  const agent = userAgent ?? '';
  if (HEADLESS_AGENT.test(agent) || brands?.some(brand => HEADLESS_AGENT.test(brand))) bits |= AUTOMATION_BITS.headless;
  if (AUTOMATION_AGENT.test(agent)) bits |= AUTOMATION_BITS.bot_agent;
  return bits;
}

/* ------------------------------------------------------------------ click rhythm */

/** More than 8 clicks a second sustained for 2 seconds means 17 clicks inside any 2 second span. */
export const RAPID_WINDOW_MS = 2000;
export const RAPID_CLICKS = 17;
/** Ten clicks on one exact point whose gaps differ by no more than this are a metronome. */
export const METRONOME_CLICKS = 10;
export const METRONOME_SPREAD_MS = 20;
export const METRONOME_MAX_GAP_MS = 5000;
/** More than 60 clicks in 30 seconds. */
export const SUSTAINED_WINDOW_MS = 30_000;
export const SUSTAINED_CLICKS = 61;
/** At least this many clicks on one exact point, and most of the batch, is a same spot pattern. */
export const SAME_SPOT_MIN = 12;
export const SAME_SPOT_SHARE = 0.8;
/** Untrusted events, unpaired clicks and stationary mouse clicks needed before the tracker reports them. */
export const UNTRUSTED_MIN = 5;
export const UNPAIRED_MIN = 5;
export const NO_MOVEMENT_MIN = 10;
/** A click counts as paired when a press began this recently. */
export const PAIRED_PRESS_MS = 1500;

const MAX_POINTS = 8;

/**
 * Watches click timing and position as clicks arrive and reports which patterns have been seen. It keeps at
 * most the last 61 timestamps and a few points, so memory stays flat however long a visit lasts. Bits are
 * never cleared: a pattern that happened happened.
 */
export class ClickRhythm {
  private recent: number[] = [];
  private points = new Map<string, number[]>();
  private seen = 0;

  observe(at: number, point: string): void {
    this.seen |= this.timing(at);
    this.seen |= this.position(at, point);
  }

  bits(): number { return this.seen; }

  private timing(at: number): number {
    let bits = 0;
    this.recent.push(at);
    if (this.recent.length > SUSTAINED_CLICKS) this.recent.shift();
    const count = this.recent.length;
    if (count >= RAPID_CLICKS && at - this.recent[count - RAPID_CLICKS] <= RAPID_WINDOW_MS) bits |= AUTOMATION_BITS.rapid_input;
    if (count >= SUSTAINED_CLICKS && at - this.recent[0] <= SUSTAINED_WINDOW_MS) bits |= AUTOMATION_BITS.sustained_clicking;
    return bits;
  }

  private position(at: number, point: string): number {
    let times = this.points.get(point);
    if (!times) {
      if (this.points.size >= MAX_POINTS) this.points.delete(this.points.keys().next().value as string);
      times = [];
      this.points.set(point, times);
    }
    times.push(at);
    if (times.length > METRONOME_CLICKS) times.shift();
    if (times.length < METRONOME_CLICKS) return 0;
    let low = Infinity;
    let high = 0;
    for (let index = 1; index < times.length; index++) {
      const gap = times[index] - times[index - 1];
      if (gap > METRONOME_MAX_GAP_MS) return 0;
      low = Math.min(low, gap);
      high = Math.max(high, gap);
    }
    return high - low <= METRONOME_SPREAD_MS ? AUTOMATION_BITS.metronome : 0;
  }
}

/** A click's exact position as a key: document pixels when known, otherwise the viewport ratios. */
export const clickPointKey = (click: { x: number; y: number; pageX?: number; pageY?: number }): string =>
  click.pageX !== undefined && click.pageY !== undefined ? `p${click.pageX},${click.pageY}` : `v${click.x},${click.y}`;

/**
 * The signals one batch's clicks show on their own: pace, rhythm and repetition. Used by the collector, which
 * sees only the clicks the tracker recorded. Pace and rhythm are tested over the batch alone.
 */
export function clickBits(clicks: readonly { timestamp: number; x: number; y: number; pageX?: number; pageY?: number }[]): number {
  if (!clicks.length) return 0;
  const rhythm = new ClickRhythm();
  const ordered = [...clicks].sort((a, b) => a.timestamp - b.timestamp);
  const spots = new Map<string, number>();
  for (const click of ordered) {
    const key = clickPointKey(click);
    rhythm.observe(click.timestamp, key);
    spots.set(key, (spots.get(key) ?? 0) + 1);
  }
  let bits = rhythm.bits();
  const most = Math.max(...spots.values());
  if (most >= SAME_SPOT_MIN && most / ordered.length >= SAME_SPOT_SHARE) bits |= AUTOMATION_BITS.same_spot;
  return bits;
}

/** The bits a batch contributes: what the tracker reported, masked, plus what the collector observed. */
export const batchAutomationBits = (reported: number | undefined, observed: number): number =>
  (Number.isInteger(reported) ? (reported as number) & AUTOMATION_MASK : 0) | observed;
